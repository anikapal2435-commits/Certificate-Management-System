    private void btnGenerateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerateActionPerformed
        String certificateNumber = txtCertificateNumber.getText();
String recipientName = txtRecipientName.getText();
String courseName = txtCourseName.getText();
String issueDate = txtIssueDate.getText();

String verificationId = "CERT-" + System.currentTimeMillis();

Certificate certificate = new Certificate(
        verificationId,
        certificateNumber,
        recipientName,
        courseName,
        issueDate
);

CertificateDAO dao = new CertificateDAO();

boolean saved = dao.saveCertificate(certificate);


if (saved) {
    try {
        String pdfPath =
            PDFGenerator.generateCertificate(certificate);

        if (pdfPath != null) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Certificate saved successfully!\n" +
                "PDF Location: " + pdfPath
            );
        } else {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Certificate saved in database.\n" +
                "PDF generation cancelled."
            );
        }

    } catch (Exception e) {
        e.printStackTrace();

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Certificate saved in database, " +
            "but PDF generation failed:\n" + e.getMessage()
        );
    }

} else {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Certificate could not be generated."
    );

}// TODO add your handling code here:
    }//GEN-LAST:event_btnGenerateActionPerformed

